function updateBestStats() {
  bestScoreEl.textContent = state.bestScore;
  bestStreakEl.textContent = state.bestStreakAllTime + 'x';
}

function getLevelLabel(score) {
  if (score >= 90) return 'Sangat Siaga';
  if (score >= 75) return 'Siaga';
  if (score >= 55) return 'Cakap';
  return 'Pemula';
}

function startGame() {
  const studentInput = document.getElementById('student-name');
  state.studentName = studentInput.value.trim() || 'Ihsan Alfaridhi';
  state.selectedClass = document.getElementById('class-select').value;

  state.activeQuestions = [...quizDatabase[state.selectedClass]];
  state.currentQuestion = 0;
  state.score = 0;
  state.correctAnswers = 0;
  state.streak = 0;
  state.bestStreak = 0;
  state.userAnswers = [];
  state.selectedOption = null;

  welcomeScreen.classList.add('hidden');
  resultScreen.classList.add('hidden');
  quizScreen.classList.remove('hidden');
  scoreBadge.style.display = 'inline-flex';
  timerBadge.style.display = 'inline-flex';

  document.getElementById('selected-class-badge').textContent = `Kelas ${state.selectedClass} SMA`;
  const classLabel = getLevelLabel(0);
  levelTagEl.textContent = classLabel;

  updateScoreDisplay();
  showQuestion();
}

function showQuestion() {
  clearInterval(state.timerId);
  const q = state.activeQuestions[state.currentQuestion];
  state.selectedOption = null;
  state.timer = 15;

  document.getElementById('question-number').textContent = `Pertanyaan ${state.currentQuestion + 1} / ${state.activeQuestions.length}`;
  document.getElementById('category-tag').textContent = q.category;
  document.getElementById('question-text').textContent = q.question;

  const progress = ((state.currentQuestion + 1) / state.activeQuestions.length) * 100;
  document.getElementById('progress-bar').style.width = `${progress}%`;

  const explanationBox = document.getElementById('explanation-box');
  explanationBox.classList.add('hidden');
  explanationBox.classList.remove('success', 'error');
  document.getElementById('next-btn').classList.add('hidden');

  const container = document.getElementById('options-container');
  container.innerHTML = '';

  q.options.forEach((opt, index) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'option-btn';
    btn.innerHTML = `
      <span class="option-letter">${String.fromCharCode(65 + index)}</span>
      <span class="option-text">${opt}</span>
    `;
    btn.onclick = () => selectOption(index);
    container.appendChild(btn);
  });

  updateTimerDisplay();
  startTimer();
}

function startTimer() {
  state.timerId = setInterval(() => {
    state.timer -= 1;
    updateTimerDisplay();

    if (state.timer <= 0) {
      clearInterval(state.timerId);
      handleTimeout();
    }
  }, 1000);
}

function updateTimerDisplay() {
  timeRemainingEl.textContent = `${state.timer}s`;
  timerBadge.style.borderColor = state.timer <= 5 ? 'rgba(248, 113, 113, 0.4)' : 'rgba(148, 163, 184, 0.18)';
}

function selectOption(index) {
  if (state.selectedOption !== null) return;
  clearInterval(state.timerId);

  const q = state.activeQuestions[state.currentQuestion];
  const isCorrect = index === q.correct;
  const buttons = document.querySelectorAll('.option-btn');

  if (isCorrect) {
    state.streak += 1;
    state.bestStreak = Math.max(state.bestStreak, state.streak);
    const timeBonus = Math.max(0, state.timer);
    const earned = 10 + timeBonus;
    state.score += earned;
    state.correctAnswers += 1;

    buttons[index].style.borderColor = 'rgba(52, 211, 153, 0.8)';
    buttons[index].style.background = 'rgba(16, 185, 129, 0.12)';
    buttons[index].querySelector('.option-letter').style.background = 'rgba(52, 211, 153, 0.9)';
    buttons[index].querySelector('.option-letter').style.color = '#06281d';
  } else {
    state.streak = 0;
    buttons[index].style.borderColor = 'rgba(248, 113, 113, 0.8)';
    buttons[index].style.background = 'rgba(239, 68, 68, 0.1)';
    buttons[index].querySelector('.option-letter').style.background = 'rgba(248, 113, 113, 0.9)';
    buttons[index].querySelector('.option-letter').style.color = '#fff';

    const correctIndex = q.correct;
    buttons[correctIndex].style.borderColor = 'rgba(52, 211, 153, 0.65)';
    buttons[correctIndex].style.background = 'rgba(16, 185, 129, 0.08)';
    buttons[correctIndex].querySelector('.option-letter').style.background = 'rgba(52, 211, 153, 0.9)';
    buttons[correctIndex].querySelector('.option-letter').style.color = '#06281d';
  }

  buttons.forEach((btn) => {
    btn.disabled = true;
    btn.style.cursor = 'default';
  });

  state.userAnswers.push({
    question: q.question,
    selected: q.options[index],
    correctAnswer: q.options[q.correct],
    isCorrect: isCorrect,
    explanation: q.explanation,
    earned: isCorrect ? 10 + Math.max(0, state.timer) : 0
  });

  updateScoreDisplay();
  showExplanation(isCorrect, q.explanation);
}

function handleTimeout() {
  if (state.selectedOption !== null) return;

  const q = state.activeQuestions[state.currentQuestion];
  const buttons = document.querySelectorAll('.option-btn');
  const correctIndex = q.correct;

  state.streak = 0;
  buttons[correctIndex].style.borderColor = 'rgba(52, 211, 153, 0.65)';
  buttons[correctIndex].style.background = 'rgba(16, 185, 129, 0.08)';
  buttons[correctIndex].querySelector('.option-letter').style.background = 'rgba(52, 211, 153, 0.9)';
  buttons[correctIndex].querySelector('.option-letter').style.color = '#06281d';

  buttons.forEach((btn) => {
    btn.disabled = true;
    btn.style.cursor = 'default';
  });

  state.selectedOption = -1;
  state.userAnswers.push({
    question: q.question,
    selected: 'Tidak terjawab',
    correctAnswer: q.options[q.correct],
    isCorrect: false,
    explanation: q.explanation,
    earned: 0
  });

  updateScoreDisplay();
  showExplanation(false, q.explanation);
}

function showExplanation(isCorrect, text) {
  const expBox = document.getElementById('explanation-box');
  const expTitle = document.getElementById('explanation-title');
  const expText = document.getElementById('explanation-text');

  expBox.classList.remove('hidden');
  expBox.classList.remove('success', 'error');

  if (isCorrect) {
    expBox.classList.add('success');
    expTitle.style.color = '#6ee7b7';
    expTitle.innerHTML = '<i class="fa-solid fa-circle-check"></i> Jawaban Tepat!';
  } else {
    expBox.classList.add('error');
    expTitle.style.color = '#fca5a5';
    expTitle.innerHTML = '<i class="fa-solid fa-circle-xmark"></i> Waktu habis / jawaban salah';
  }

  expText.textContent = text;
  document.getElementById('next-btn').classList.remove('hidden');
}

function updateScoreDisplay() {
  currentScoreEl.textContent = `Skor: ${state.score}`;
  document.getElementById('streak-value').textContent = `${state.streak}x`;
  const currentLevel = getLevelLabel(state.score);
  levelTagEl.textContent = currentLevel;
}

function nextQuestion() {
  state.currentQuestion += 1;
  if (state.currentQuestion < state.activeQuestions.length) {
    showQuestion();
  } else {
    showResults();
  }
}

function showResults() {
  clearInterval(state.timerId);
  const totalQuestions = state.activeQuestions.length;
  const percentage = Math.round((state.correctAnswers / totalQuestions) * 100);
  state.bestScore = Math.max(state.bestScore, state.score);
  state.bestStreakAllTime = Math.max(state.bestStreakAllTime, state.bestStreak);

  localStorage.setItem('siagaBestScore', String(state.bestScore));
  localStorage.setItem('siagaBestStreak', String(state.bestStreakAllTime));

  quizScreen.classList.add('hidden');
  resultScreen.classList.remove('hidden');

  document.getElementById('final-score').textContent = state.score;
  document.getElementById('correct-count').textContent = `${state.correctAnswers} / ${totalQuestions}`;
  document.getElementById('final-streak').textContent = `${state.bestStreak}x`;
  document.getElementById('result-student-info').textContent = `${state.studentName} | Kelas ${state.selectedClass} SMA`;

  const resultIcon = document.getElementById('result-icon');
  const resultMessage = document.getElementById('result-message');
  const rankLabel = document.getElementById('rank-label');
  const achievement = document.getElementById('achievement-text');

  state.finalRank = getLevelLabel(percentage);
  rankLabel.textContent = state.finalRank;

  if (percentage >= 80) {
    resultIcon.className = 'result-icon';
    resultIcon.style.background = 'rgba(52, 211, 153, 0.12)';
    resultIcon.style.borderColor = 'rgba(52, 211, 153, 0.35)';
    resultIcon.style.color = '#6ee7b7';
    resultIcon.innerHTML = '<i class="fa-solid fa-trophy"></i>';
    resultMessage.textContent = `Luar biasa, ${state.studentName}! Kamu memiliki pemahaman yang sangat kuat tentang mitigasi bencana.`;
    achievement.textContent = 'Achievement: Siaga Tangguh';
  } else if (percentage >= 60) {
    resultIcon.className = 'result-icon';
    resultIcon.style.background = 'rgba(251, 191, 36, 0.12)';
    resultIcon.style.borderColor = 'rgba(251, 191, 36, 0.34)';
    resultIcon.style.color = '#fbbf24';
    resultIcon.innerHTML = '<i class="fa-solid fa-medal"></i>';
    resultMessage.textContent = `Bagus, ${state.studentName}! Kamu sudah cukup siap, tapi masih ada ruang untuk terus belajar.`;
    achievement.textContent = 'Achievement: Cakap Mitigasi';
  } else {
    resultIcon.className = 'result-icon';
    resultIcon.style.background = 'rgba(248, 113, 113, 0.12)';
    resultIcon.style.borderColor = 'rgba(248, 113, 113, 0.34)';
    resultIcon.style.color = '#fca5a5';
    resultIcon.innerHTML = '<i class="fa-solid fa-triangle-exclamation"></i>';
    resultMessage.textContent = `Tetap semangat, ${state.studentName}! Pelajari materi kembali agar kesiapsiagaanmu meningkat.`;
    achievement.textContent = 'Achievement: Siap belajar lagi';
  }

  updateBestStats();
}

