function downloadReport() {
  const totalQuestions = state.activeQuestions.length;
  let content = '====================================================\n';
  content += '   LAPORAN HASIL QUIZ MITIGASI BENCANA ALAM\n';
  content += '====================================================\n';
  content += `Nama Peserta     : ${state.studentName}\n`;
  content += `Kelas            : Kelas ${state.selectedClass} SMA\n`;
  content += `Tanggal          : ${new Date().toLocaleString('id-ID')}\n`;
  content += `Skor Akhir       : ${state.score}\n`;
  content += `Jawaban Benar    : ${state.correctAnswers} / ${totalQuestions}\n`;
  content += `Best Score       : ${state.bestScore}\n`;
  content += `Best Streak      : ${state.bestStreakAllTime}x\n`;
  content += `Peringkat        : ${state.finalRank}\n`;
  content += '----------------------------------------------------\n\n';
  content += 'RINCIAN JAWABAN ANDA:\n';

  state.userAnswers.forEach((item, index) => {
    content += `\n${index + 1}. ${item.question}\n`;
    content += `   Pilihan Anda    : ${item.selected}\n`;
    content += `   Jawaban Benar   : ${item.correctAnswer}\n`;
    content += `   Status         : ${item.isCorrect ? 'BENAR' : 'SALAH'}\n`;
    content += `   Penjelasan     : ${item.explanation}\n`;
  });

  content += '\n* Tetap waspada dan kenali potensi bencana di lingkunganmu. *\n';

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Laporan_Quiz_Siaga_Bencana_${state.studentName.replace(/\s+/g, '_')}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

